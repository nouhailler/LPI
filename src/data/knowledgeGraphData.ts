import { GlossaryItemType } from '../types';

export type ConceptRelationType =
  | 'controls'          // controls / commande
  | 'manages'           // manages / administre
  | 'switches'          // switches / bascule
  | 'orchestrates'      // orchestrates / orchestre
  | 'inspects_logs'     // inspects logs / inspecte les journaux
  | 'troubleshoots'     // used for troubleshooting / permet de dépanner
  | 'configured_by'     // configured by / configuré par
  | 'queries'           // queries / interroge
  | 'depends_on'        // depends on / dépend de
  | 'formats'           // formats / formate
  | 'mounts_to'         // mounts to / monté sur
  | 'filters'           // filters / filtre
  | 'monitors'          // monitors / surveille
  | 'authenticates'     // authenticates / authentifie
  | 'secures'           // secures / sécurise
  | 'generates'         // generates / génère
  | 'resolves'          // resolves / résout
  | 'initializes'       // initializes / initialise
  | 'related_to';       // related to / associé à

export interface ConceptRelation {
  sourceTerm: string;
  targetTerm: string;
  relationType: ConceptRelationType;
  labelEn: string;
  labelFr: string;
  descriptionEn: string;
  descriptionFr: string;
}

