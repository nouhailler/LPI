// Helper to get connected relations for a given term (case-insensitive)
export function getConceptRelations(term: string): {
  outgoing: ConceptRelation[];
  incoming: ConceptRelation[];
  all: ConceptRelation[];
} {
  const normalized = term.trim().toLowerCase();
  
  const outgoing = allConceptRelations.filter(
    (r) => r.sourceTerm.toLowerCase() === normalized
  );
  
  const incoming = allConceptRelations.filter(
    (r) => r.targetTerm.toLowerCase() === normalized
  );

  return {
    outgoing,
    incoming,
    all: [...outgoing, ...incoming],
  };
}

// Helper to get or fallback a knowledge node
export function getKnowledgeNode(term: string): KnowledgeNodeData | null {
  const normalized = term.trim().toLowerCase();
  for (const [key, node] of Object.entries(allKnowledgeNodes)) {
    if (key.toLowerCase() === normalized || node.term.toLowerCase() === normalized) {
      return node;
    }
  }
  return null;
}

// Find all connected nodes within 1 or 2 hops
export function getConnectedNeighborhood(term: string, maxDepth: number = 1): {
  nodes: KnowledgeNodeData[];
  relations: ConceptRelation[];
} {
  const rootNode = getKnowledgeNode(term);
  if (!rootNode) return { nodes: [], relations: [] };

  const collectedNodeIds = new Set<string>([rootNode.id]);
  const collectedRelations = new Set<ConceptRelation>();

  const currentLevel = [rootNode.id];

  for (let d = 0; d < maxDepth; d++) {
    const nextLevel: string[] = [];

    for (const curId of currentLevel) {
      const { outgoing, incoming } = getConceptRelations(curId);

      for (const rel of outgoing) {
        collectedRelations.add(rel);
        const targetNode = getKnowledgeNode(rel.targetTerm);
        if (targetNode && !collectedNodeIds.has(targetNode.id)) {
          collectedNodeIds.add(targetNode.id);
          nextLevel.push(targetNode.id);
        }
      }

      for (const rel of incoming) {
        collectedRelations.add(rel);
        const sourceNode = getKnowledgeNode(rel.sourceTerm);
        if (sourceNode && !collectedNodeIds.has(sourceNode.id)) {
          collectedNodeIds.add(sourceNode.id);
          nextLevel.push(sourceNode.id);
        }
      }
    }

    currentLevel.length = 0;
    currentLevel.push(...nextLevel);
  }

  const nodes: KnowledgeNodeData[] = [];
  for (const id of collectedNodeIds) {
    const n = getKnowledgeNode(id);
    if (n) nodes.push(n);
  }

  return {
    nodes,
    relations: Array.from(collectedRelations),
  };
}
