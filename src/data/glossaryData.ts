/**
 * Builds an aggregated, non-duplicate list of glossary terms by combining
 * the hand-crafted curated deep entries with all auto-indexed objective terms
 * across LPIC-1, LPIC-2, LPIC-3 (Exams 101, 102, 201, 202, 300, 303, 305, 306).
 */
export function getAllGlossaryEntries(): GlossaryEntry[] {
  const map = new Map<string, GlossaryEntry>();

  // 1. Insert curated rich entries first
  for (const entry of curatedGlossaryEntries) {
    const key = entry.term.toLowerCase().trim();
    map.set(key, entry);
  }

  // 2. Scan all LPIC topics and objectives for additional terms and files
  for (const topic of allLpicTopicsData) {
    const cert: 'lpic-1' | 'lpic-2' | 'lpic-3' = topic.certification || (
      topic.topicNumber >= 300 ? 'lpic-3' : topic.topicNumber >= 200 ? 'lpic-2' : 'lpic-1'
    );

    for (const obj of topic.objectives) {
      // Index terms and utilities
      for (const term of obj.termsAndUtilities || []) {
        const cleanTerm = term.trim();
        if (!cleanTerm) continue;
        const key = cleanTerm.toLowerCase();

        if (!map.has(key)) {
          const isFile = cleanTerm.startsWith('/') || cleanTerm.endsWith('/') || cleanTerm.includes('.conf') || cleanTerm.includes('.d');
          const isCommand = !isFile && !cleanTerm.includes(' ') && !cleanTerm.includes('(');
          const type = isFile ? 'file' : isCommand ? 'command' : 'concept';

          map.set(key, {
            id: `auto-${topic.topicNumber}-${cleanTerm.replace(/[^a-zA-Z0-9]/g, '-').toLowerCase()}`,
            term: cleanTerm,
            type,
            certification: cert,
            examId: topic.examId,
            objectiveId: obj.id,
            topicNumber: topic.topicNumber,
            topicTitle: topic.title,
            category: mapCategory(topic.title, topic.topicNumber),
            definition: `Core utility/term specified under LPIC Objective ${obj.id}: ${obj.title}. Key knowledge area for Exam ${topic.examId.replace('exam-', '')}.`,
            syntaxOrLocation: isFile ? `Path: ${cleanTerm}` : `Command / Utility: ${cleanTerm}`,
            exampleSnippet: isFile ? `ls -la ${cleanTerm}` : `${cleanTerm} --help`,
            exampleExplanation: `Refer to Objective ${obj.id} in the Learning Modules tab for full syntax, flags, and exam checkpoints.`,
            relatedTerms: [topic.title, `Objective ${obj.id}`],
          });
        }
      }

      // Index files and paths
      for (const filePath of obj.filesAndPaths || []) {
        const cleanFile = filePath.trim();
        if (!cleanFile) continue;
        const key = cleanFile.toLowerCase();

        if (!map.has(key)) {
          map.set(key, {
            id: `auto-file-${topic.topicNumber}-${cleanFile.replace(/[^a-zA-Z0-9]/g, '-').toLowerCase()}`,
            term: cleanFile,
            type: 'file',
            certification: cert,
            examId: topic.examId,
            objectiveId: obj.id,
            topicNumber: topic.topicNumber,
            topicTitle: topic.title,
            category: mapCategory(topic.title, topic.topicNumber),
            definition: `Key configuration file or virtual filesystem path specified in LPIC Objective ${obj.id}: ${obj.title}.`,
            syntaxOrLocation: cleanFile,
            exampleSnippet: cleanFile.endsWith('/') ? `ls -la ${cleanFile}` : `sudo cat ${cleanFile} | head -n 20`,
            exampleExplanation: `Essential file path tested under Topic ${topic.topicNumber} (${topic.title}).`,
            relatedTerms: [topic.title, `Objective ${obj.id}`],
          });
        }
      }
    }
  }

  // Return sorted alphabetically
  return Array.from(map.values()).sort((a, b) => a.term.localeCompare(b.term, undefined, { sensitivity: 'base' }));
}

function mapCategory(topicTitle: string, topicNum: number): string {
  const lower = topicTitle.toLowerCase();
  if (lower.includes('network') || lower.includes('dns') || lower.includes('bind')) return 'Networking & DNS';
  if (lower.includes('storage') || lower.includes('filesystem') || lower.includes('device') || lower.includes('raid') || lower.includes('lvm') || lower.includes('drbd')) return 'Storage & Filesystems';
  if (lower.includes('security') || lower.includes('crypt') || lower.includes('access control') || lower.includes('selinux') || lower.includes('audit')) return 'Security & Hardening';
  if (lower.includes('virtualization') || lower.includes('container') || lower.includes('docker') || lower.includes('qemu') || lower.includes('xen') || lower.includes('provisioning') || lower.includes('terraform')) return 'Virtualization & Containers';
  if (lower.includes('cluster') || lower.includes('high availability') || lower.includes('pacemaker') || lower.includes('ceph') || lower.includes('gluster') || lower.includes('lvs')) return 'High Availability & Clustering';
  if (lower.includes('samba') || lower.includes('ldap') || lower.includes('kerberos') || lower.includes('winbind') || lower.includes('freeipa')) return 'Directory Services & Samba';
  if (lower.includes('kernel') || lower.includes('hardware') || lower.includes('architecture') || lower.includes('boot')) return 'Kernel & Hardware';
  if (lower.includes('mail') || lower.includes('web') || lower.includes('apache') || lower.includes('nginx') || lower.includes('service')) return 'Essential Services';
  return 'System Administration';
}
